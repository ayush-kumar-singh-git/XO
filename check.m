function [r] = check(B)
    r  = 0;
    if B(1,1) == B(1,2) && B(1,2) == B(1,3)
        r = B(1,1);
    elseif B(2,1) == B(2,2) && B(2,2) == B(2,3)
        r = B(2,1);
    elseif B(3,1) == B(3,2) && B(3,2) == B(3,3)
        r = B(3,1);
    elseif B(1,1) == B(2,1) && B(2,1) == B(3,1)
        r = B(1,1);
    elseif B(1,2) == B(2,2) && B(2,2) == B(3,2)
        r = B(1,2);
    elseif B(1,3) == B(2,3) && B(2,3) == B(3,3)
        r = B(1,3);
    elseif B(1,1) == B(2,2) && B(2,2) == B(3,3)
        r = B(1,1);
    elseif B(1,3) == B(2,2) && B(2,2) == B(3,1)
        r = B(1,3);
    end
end
